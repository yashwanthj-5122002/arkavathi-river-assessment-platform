# ARKAVATHI FINAL INTRODUCTION + LOOPING VIDEO PATCH
# Frontend-only incremental patch. Does not modify backend files.

$ErrorActionPreference = "Stop"

$ProjectRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$FrontendRoot = Join-Path $ProjectRoot "frontend"
$IntroPath = Join-Path $FrontendRoot "src\components\IntroductionSection.tsx"
$VideoComponentPath = Join-Path $FrontendRoot "src\components\ArkavathiVideoShowcase.tsx"
$VideosDir = Join-Path $FrontendRoot "public\videos"
$PlaylistPath = Join-Path $VideosDir "video-playlist.json"

if (-not (Test-Path $FrontendRoot)) { throw "frontend folder not found beside this patch: $FrontendRoot" }
if (-not (Test-Path $IntroPath)) { throw "IntroductionSection.tsx not found: $IntroPath" }
if (-not (Test-Path $VideoComponentPath)) { throw "ArkavathiVideoShowcase.tsx not found: $VideoComponentPath" }
if (-not (Test-Path $VideosDir)) { throw "frontend/public/videos folder not found: $VideosDir" }

$CurrentIntro = Get-Content $IntroPath -Raw
if ($CurrentIntro -notmatch "Collaboration" -or $CurrentIntro -notmatch "Study Area Map") {
    throw "This patch expects the previously applied Overview/Introduction patch. Collaboration or Study Area Map was not found. No files were changed."
}

$SupportedVideoExtensions = @('.mp4', '.webm', '.m4v', '.mov')
$AllVideos = Get-ChildItem -Path $VideosDir -File | Where-Object { $SupportedVideoExtensions -contains $_.Extension.ToLowerInvariant() }
$VideoFile = $AllVideos | Where-Object { $_.BaseName -ieq 'Dashboard_Drone_Video' } | Select-Object -First 1
if (-not $VideoFile) {
    $VideoFile = $AllVideos | Where-Object { $_.BaseName -like 'Dashboard*Drone*Video*' } | Select-Object -First 1
}
if (-not $VideoFile) {
    $Found = if ($AllVideos) { ($AllVideos | ForEach-Object { $_.Name }) -join ', ' } else { '<none>' }
    throw "Dashboard_Drone_Video was not found in frontend/public/videos. Found video files: $Found. Put the dashboard drone video in that folder, then run this patch again. No files were changed."
}

$TimeStamp = Get-Date -Format "yyyyMMdd_HHmmss"
$BackupDir = Join-Path $ProjectRoot "patch_backups\final_intro_video_$TimeStamp"
New-Item -ItemType Directory -Path $BackupDir -Force | Out-Null

Copy-Item $IntroPath (Join-Path $BackupDir "IntroductionSection.tsx") -Force
Copy-Item $VideoComponentPath (Join-Path $BackupDir "ArkavathiVideoShowcase.tsx") -Force
$HadPlaylist = Test-Path $PlaylistPath
if ($HadPlaylist) { Copy-Item $PlaylistPath (Join-Path $BackupDir "video-playlist.json") -Force }

